		_ = sb.Append(indent)
			.Append("_ = await handler.HandleAsync(new ")
			.Append(requestFullyQualifiedName)
			.Append('(')
			.Append(requestArgs)
			.AppendLine("), cancellationToken).ConfigureAwait(false);");
		_ = sb.Append(indent).AppendLine("return true;");
	}

	private static void EmitParse(StringBuilder sb, RequestParameterModel parameter, int index, string indent)
	{
		var parseCall = parameter.Kind switch
		{
			BindableParameterKind.String => null,
			BindableParameterKind.Int =>
				"global::Vexel.Telegram.Handlers.Routing.CommandArgumentBinder.TryParseInt(tokens[" + index + "], out var p" + index + ")",
			BindableParameterKind.Long =>
				"global::Vexel.Telegram.Handlers.Routing.CommandArgumentBinder.TryParseLong(tokens[" + index + "], out var p" + index + ")",
			BindableParameterKind.Bool =>
				"global::Vexel.Telegram.Handlers.Routing.CommandArgumentBinder.TryParseBool(tokens[" + index + "], out var p" + index + ")",
			BindableParameterKind.Decimal =>
				"global::Vexel.Telegram.Handlers.Routing.CommandArgumentBinder.TryParseDecimal(tokens[" + index + "], out var p" + index + ")",
			BindableParameterKind.Enum =>
				"global::Vexel.Telegram.Handlers.Routing.CommandArgumentBinder.TryParseEnum<"
				+ parameter.FullyQualifiedTypeName
				+ ">(tokens[" + index + "], out var p" + index + ")",
			_ => throw new InvalidOperationException("Unexpected kind " + parameter.Kind),
		};

		if (parseCall is null)
		{
			// Token already a string; no parse step.
			return;
		}

		_ = sb.Append(indent).Append("if (!").Append(parseCall).AppendLine(")");
		_ = sb.Append(indent).AppendLine("{");
		_ = sb.Append(indent).AppendLine("\treturn false;");
		_ = sb.Append(indent).AppendLine("}");
		_ = sb.AppendLine();
	}

