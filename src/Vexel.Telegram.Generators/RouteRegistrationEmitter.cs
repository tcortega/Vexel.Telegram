			_ = sb.AppendLine("\t\t\t},");
		}

		_ = sb.AppendLine("\t\t};");
	}

	private static void EmitCommandBinderBody(StringBuilder sb, CommandRouteModel command, string indent)
	{
		if (command.Parameters.Count == 0)
		{
			EmitResolveAndInvoke(sb, command.HandlerFullyQualifiedName, command.RequestFullyQualifiedName, indent, requestArgs: string.Empty);
			return;
		}

		if (command.Parameters is [{ Kind: BindableParameterKind.String }])
		{
			// Single string: whole remainder (possibly empty).
			EmitResolveAndInvoke(sb, command.HandlerFullyQualifiedName, command.RequestFullyQualifiedName, indent, requestArgs: "payload");
			return;
		}

		var trailingTakesRest = command.Parameters[^1].IsTrailingString;
		_ = sb.Append(indent)
			.Append("if (!global::Vexel.Telegram.Handlers.Routing.CommandArgumentBinder.TryTokenize(payload, ")
			.Append(command.Parameters.Count)
			.Append(", trailingTakesRest: ")
			.Append(trailingTakesRest ? "true" : "false")
			.AppendLine(", out var tokens))");
		_ = sb.Append(indent).AppendLine("{");
		_ = sb.Append(indent).AppendLine("\treturn false;");
		_ = sb.Append(indent).AppendLine("}");
		_ = sb.AppendLine();

		for (var i = 0; i < command.Parameters.Count; i++)
		{
			EmitParse(sb, command.Parameters[i], i, indent);
		}

		var args = new StringBuilder();
		for (var i = 0; i < command.Parameters.Count; i++)
		{
			if (i > 0)
			{
				_ = args.Append(", ");
			}

			_ = args.Append(command.Parameters[i].Kind == BindableParameterKind.String
				? "tokens[" + i + "]"
				: "p" + i);
		}

		EmitResolveAndInvoke(sb, command.HandlerFullyQualifiedName, command.RequestFullyQualifiedName, indent, args.ToString());
	}

	private static void EmitStringOrEmptyBinderBody(
		StringBuilder sb,
		string handlerFullyQualifiedName,
		string requestFullyQualifiedName,
		bool hasStringParameter,
		string indent)
	{
		// Empty record: ignore payload. Single string: whole payload (possibly empty).
		var requestArgs = hasStringParameter ? "payload" : string.Empty;
		EmitResolveAndInvoke(sb, handlerFullyQualifiedName, requestFullyQualifiedName, indent, requestArgs);
	}

